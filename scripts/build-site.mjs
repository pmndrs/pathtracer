#!/usr/bin/env node
/**
 * Builds the GitHub Pages site: the pmndrs/docs site at the root, the examples gallery under `examples/`, and (with `--classroom`) the
 * Classroom showcase under `examples/showcase/classroom/`. Also writes docs/getting-started/examples.mdx from examples/catalog.ts.
 *
 *   node scripts/build-site.mjs                      # examples.mdx + the gallery into dist/site (base /pathtracer/)
 *   node scripts/build-site.mjs --docs --classroom   # everything (CI; the Classroom needs `python3 bench/hero/prepare.py classroom`)
 *   node scripts/build-site.mjs --check              # fail if examples.mdx is stale (no build)
 *
 * Options: --out <dir> (default dist/site), --base <path> (default PAGES_BASE or /pathtracer/), --docs, --classroom, --check.
 * The docs step reads the same environment variables as pmndrs/docs' reusable workflow (NEXT_PUBLIC_LIBNAME, ...): CI sets them.
 */
import { spawnSync } from 'node:child_process';
import { cpSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { CATEGORIES, EXAMPLES, SITE_URL, STATUS_LABELS } from '../examples/catalog.ts';

const root = fileURLToPath(new URL('..', import.meta.url));
const args = process.argv.slice(2);
const flag = (name) => args.includes(name);
const value = (name, fallback) => {
  const i = args.indexOf(name);
  return i >= 0 && args[i + 1] ? args[i + 1] : fallback;
};
const out = resolve(root, value('--out', 'dist/site'));
const base = `/${value('--base', process.env.PAGES_BASE ?? '/pathtracer/').replace(/^\/+|\/+$/g, '')}/`.replace(/^\/\/$/, '/');

/** docs/getting-started/examples.mdx: the catalog as tables, one per category. */
function examplesMdx() {
  const gallery = new URL('examples/', SITE_URL).href;
  const cell = (s) => s.replace(/\|/g, '\\|').replace(/\n/g, ' ');
  const lines = [
    '---',
    'title: Examples',
    'description: Every example, one page each, with its source.',
    'nav: 6',
    '---',
    '',
    '{/* Generated by scripts/build-site.mjs from examples/catalog.ts: edit the catalog, then run `node scripts/build-site.mjs`. */}',
    '',
    `The examples run in your browser: [open the gallery](${gallery}). Each page has its source on GitHub, linked from its top bar.`,
    '',
    'Run them locally with live library sources:',
    '',
    '```sh',
    'pnpm install',
    'pnpm examples    # http://localhost:5310',
    '```',
    '',
  ];
  for (const category of CATEGORIES) {
    const entries = EXAMPLES.filter((e) => e.category === category.id);
    if (!entries.length) continue;
    lines.push(`## ${category.title}`, '', category.blurb, '', '| Example | What it shows | Status |', '| --- | --- | --- |');
    for (const e of entries) {
      const status = e.status === 'stable' ? '' : `**${STATUS_LABELS[e.status].label}**`;
      lines.push(`| [${cell(e.title)}](${new URL(e.path, gallery).href}) | ${cell(e.summary)} | ${status} |`);
    }
    lines.push('');
  }
  lines.push('**Experimental**: ' + STATUS_LABELS.experimental.blurb + ' **Research**: ' + STATUS_LABELS.research.blurb, '');
  return lines.join('\n');
}

function run(command, commandArgs, env = {}) {
  console.log(`\n> ${command} ${commandArgs.join(' ')}`);
  const result = spawnSync(command, commandArgs, { cwd: root, stdio: 'inherit', env: { ...process.env, ...env } });
  if (result.status !== 0) process.exit(result.status ?? 1);
}

const mdxPath = join(root, 'docs/getting-started/examples.mdx');
const mdx = examplesMdx();
if (flag('--check')) {
  let current = '';
  try {
    current = readFileSync(mdxPath, 'utf8');
  } catch {
    // missing counts as stale
  }
  if (current !== mdx) {
    console.error('docs/getting-started/examples.mdx is stale: run `node scripts/build-site.mjs`');
    process.exit(1);
  }
  console.log('docs/getting-started/examples.mdx is up to date');
  process.exit(0);
}
writeFileSync(mdxPath, mdx);
console.log(`wrote ${mdxPath}`);

if (flag('--docs')) {
  // pmndrs/docs builds every .md and .mdx under its folder (plain .md included, as pages and as /md/ exports), so it gets a copy of
  // docs/ without docs/internal/: the internal notes stay out of the site. Paths inside the copy are the same as in docs/, so the
  // edit and source links (EDIT_BASEURL, MDX_BASEURL) still point at the repository. BASE_PATH has no trailing slash.
  const staged = join(root, 'dist/.docs-src');
  rmSync(staged, { recursive: true, force: true });
  cpSync(join(root, 'docs'), staged, { recursive: true, filter: (source) => !source.startsWith(join(root, 'docs/internal')) });
  run('npx', ['-y', `@pmndrs/docs@${process.env.PMNDRS_DOCS_VERSION ?? '4'}`, 'build', staged, out, '--format', 'website'], { BASE_PATH: base.replace(/\/$/, '') });
}
run('pnpm', ['--filter', '@pathtracer/examples', 'build'], { EXAMPLES_BASE: `${base}examples/`, EXAMPLES_OUT: join(out, 'examples') });
if (flag('--classroom')) run('node', ['bench/hero/build-pages.mjs'], { HERO_OUT: join(out, 'examples/showcase/classroom'), PAGES_BASE: `${base}examples/showcase/classroom` });
console.log(`\nsite in ${out} (base ${base})`);
